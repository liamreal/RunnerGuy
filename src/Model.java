public class Model {
	
	 private  PlayerLogic player;
	 private  EnemyLogicManager enemies;
	 private Controller controller = Controller.getInstance();
	 private  CopyOnWriteArrayList<GameObject> EnemiesList  = new CopyOnWriteArrayList<GameObject>();
	 private  CopyOnWriteArrayList<GameObject> BulletList  = new CopyOnWriteArrayList<GameObject>();
	 private int Score=0; 

	public Model() {
		//setup game world 
		// Player= new PlayerObject();
		player = new PlayerLogic(new PlayerObject());
		//Enemies  starting with four 

		enemies = new EnemyLogicManager();
		
		EnemiesList.add(new EnemyObject(EnemyType.BASIC));
		EnemiesList.add(new EnemyObject(EnemyType.ADVANCED));
		// EnemiesList.add(new EnemyObject(50,50,new Point3f(((float)Math.random()*50+500 ),0,0)));
		
	}
	
	// This is the heart of the game , where the model takes in all the inputs ,decides the outcomes and then changes the model accordingly. 
	public void gamelogic() 
	{
		// Player Logic first 
		playerLogic(); 
		// Enemy Logic next
		enemyLogic();
		// Bullets move next 
		bulletLogic();
		// interactions between objects 
		gameLogic(); 
	   
	}

	private void gameLogic() {
		// this is a way to increment across the array list data structure 

		
		// see if they hit anything 
		// using enhanced for-loop style as it makes it alot easier both code wise and reading wise too 
		for (GameObject temp : EnemiesList) 
		{
			for (GameObject Bullet : BulletList) 
			{
				if ( Math.abs(temp.getCentre().getX()- Bullet.getCentre().getX())< temp.getWidth() 
					&& Math.abs(temp.getCentre().getY()- Bullet.getCentre().getY()) < temp.getHeight())
				{
					EnemiesList.remove(temp);
					BulletList.remove(Bullet);
					Score++;
				}  
			}
		}
		
	}

	private void enemyLogic() {
		// // monitor number of enemies in list
		// System.out.println(String.format("Num of enemies: %d", EnemiesList.size()));
		// TODO Auto-generated method stub
		for (GameObject temp : EnemiesList) 
		{
		    // Move enemies 
			  
			temp.getCentre().ApplyVector(new Vector3f(0,-1,0));
			 
			 
			//see if they get to the bottom of the screen (remember 0 is the top) 
			if (temp.getCentre().getY()>= GameDisplay.getDisplayY())  // current boundary need to pass value to model 
			{
				EnemiesList.remove(temp);
				
				// enemies win so score decreased 
				Score--;
			} 
		}
		
		if (EnemiesList.size()<2)
		{
			while (EnemiesList.size()<6)
			{         
				EnemiesList.add(new EnemyObject(EnemyType.BASIC)); 
				// EnemiesList.add(new EnemyObject(50,50,new Point3f(((float)Math.random()*1000),0,0))); 
			}
		}
	}

	private void bulletLogic() {
		// TODO Auto-generated method stub
		// move bullets 
		
		// // monitor number of bullets in list
		// System.out.println(String.format("Num of bullets: %d", BulletList.size()));
	  
		for (GameObject temp : BulletList) 
		{
		    // move bullet down Y axis
			temp.getCentre().ApplyVector(new Vector3f(0,1,0));
			//see if they hit anything 
			
			// once bullet fully off-screen, remove
			if (temp.getCentre().getY()<=-temp.getHeight())
			{
			 	BulletList.remove(temp);
			} 

		} 
		
	}

	private void playerLogic() {
		
		// smoother animation is possible if we make a target position  // done but may try to change things for students  
		 
		//check for movement and if you fired a bullet 
		player.move();
		
		if(Controller.getInstance().isKeySpacePressed())
		{
			CreateBullet();
			Controller.getInstance().setKeySpacePressed(false);
		} 
		
	}

	private void CreateBullet() {
		// BulletList.add(new GameObject("res/Bullet.png",32,64,new Point3f(Player.getCentre().getX(),Player.getCentre().getY(),0.0f)));
		BulletList.add(new BulletObject(player.getGameObject()));
	}

	public GameObject getPlayer() {
		return player.getGameObject();
	}

	public CopyOnWriteArrayList<GameObject> getEnemies() {
		return EnemiesList;
	}
	
	public CopyOnWriteArrayList<GameObject> getBullets() {
		return BulletList;
	}

	public int getScore() { 
		return Score;
	}
 

}


