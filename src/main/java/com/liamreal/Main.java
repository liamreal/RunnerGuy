// useful tutorial for having JPanel size match JFrame:
// 		https://medium.com/@nhesanda/lets-make-a-2d-rpg-game-with-java-swing-01-2cf48cc221b1

public class Main {
	private final JFrame frame;
	private final Model world;
	private final Viewer canvas;
	private final GameLoop gameLoop;
	  
	public Main() {
		// create instances of game objects
		frame = new JFrame("Runner Guy");
		world = new Model();
		canvas = new Viewer(world);
		gameLoop = new GameLoop(world, canvas);
		// create game frame
		frame.setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE);
		frame.setResizable(false);
		frame.add(canvas);
		frame.pack();
		frame.setLocationRelativeTo(null);
		frame.setVisible(true);
	}

	public void start() {
		this.gameLoop.start();
	}

	public static void main(String[] args) {
		Main game = new Main();
		game.start();
	} 
}

